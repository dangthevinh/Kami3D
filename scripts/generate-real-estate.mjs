#!/usr/bin/env node
/**
 * Generates the Data2Map real-estate sample: `data/data2map-real-estate.json`.
 *
 *   node scripts/generate-real-estate.mjs           # write the file
 *   node scripts/generate-real-estate.mjs --check   # fail if it is out of date (CI)
 *
 * ## What this is
 *
 * **Simulated**, and every feature says so. Land prices in Vietnam are published as legal
 * documents and zoning as drawings; there is no open machine-readable layer for either, so the
 * honest options were a labelled simulation or no page at all. The page is real - the layers,
 * the scoring, the satellite base and the amenity overlay all work - and the price surface is
 * an artefact that advertises itself as one.
 *
 * The real data arrives through the admin import path (`/admin/geodata`, or
 * `npm run geodata:import`): upload a GeoJSON of parcels with a price attribute and it replaces
 * this file layer by layer. That is why the sample is shaped like the real thing - hexes with a
 * `price_vnd_m2` property, parcels with a `zone` property - rather than like a mock.
 *
 * ## Why hexes
 *
 * A price surface is a raster in disguise. Turf (already a dependency) builds the grid, MapLibre
 * fills it, and no extra renderer is needed - see docs/DATA2MAP.md for why deck.gl is not here.
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { hexGrid } from "@turf/turf";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT_FILE = join(ROOT, "data", "data2map-real-estate.json");

/** Ho Chi Minh City, roughly District 1 out to the ring road. */
const AREA = { west: 106.62, south: 10.7, east: 106.87, north: 10.86 };
const CENTRE = { lng: 106.703, lat: 10.776 };

const SOURCE = "Kami3D synthetic";
const ATTRIBUTION = "Simulated land prices, zoning parcels and flood zones generated by Kami3D. Not a published price table or planning map.";

/** Deterministic noise, so regenerating the file is a no-op in git. */
function noise(seed, index) {
  const value = Math.sin(seed * 12.9898 + index * 78.233) * 43758.5453;
  return value - Math.floor(value);
}

function seedFrom(text) {
  let hash = 2166136261;
  for (let i = 0; i < text.length; i += 1) {
    hash ^= text.charCodeAt(i);
    hash = Math.imul(hash, 16777619);
  }
  return Math.abs(hash % 1000);
}

const rad = Math.PI / 180;

function distanceKm(a, b) {
  const dLat = (b.lat - a.lat) * rad;
  const dLng = (b.lng - a.lng) * rad;
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(a.lat * rad) * Math.cos(b.lat * rad) * Math.sin(dLng / 2) ** 2;
  return 2 * 6371 * Math.asin(Math.min(1, Math.sqrt(h)));
}

/**
 * A price per square metre: distance decay from the centre, plus a deterministic wobble.
 *
 * The shape is the one every city has - central land costs more - and the numbers are invented.
 * VND per square metre, which is how Vietnamese listings quote land.
 */
function priceFor(centre, index) {
  const km = distanceKm(centre, CENTRE);
  const base = 180_000_000 * Math.exp(-km / 4.2) + 18_000_000;
  const wobble = 0.75 + noise(seedFrom(`${centre.lng},${centre.lat}`), index) * 0.5;
  return Math.round((base * wobble) / 100_000) * 100_000;
}

function hexFeatures() {
  const grid = hexGrid([AREA.west, AREA.south, AREA.east, AREA.north], 1.6, { units: "kilometers" });
  const features = [];

  grid.features.forEach((hex, index) => {
    const ring = hex.geometry.coordinates[0];
    const lng = ring.reduce((sum, point) => sum + point[0], 0) / ring.length;
    const lat = ring.reduce((sum, point) => sum + point[1], 0) / ring.length;
    const centre = { lng, lat };
    const price = priceFor(centre, index);

    features.push({
      type: "Feature",
      properties: {
        layer: "land_price",
        hex_id: `h${index}`,
        price_vnd_m2: price,
        distance_km: Math.round(distanceKm(centre, CENTRE) * 100) / 100,
        source: SOURCE,
        license: "CC0",
        synthetic: true,
        note: "Simulated price. Vietnam publishes land price tables as legal documents, not as open polygons.",
      },
      geometry: hex.geometry,
    });
  });

  return features;
}

/** A parcel grid: rectangles with a designation, the shape a real zoning layer has. */
function zoningFeatures() {
  const zones = ["residential", "commercial", "mixed", "industrial", "public", "green"];
  const rows = 6;
  const columns = 8;
  const width = (AREA.east - AREA.west) / columns;
  const height = (AREA.north - AREA.south) / rows;
  const features = [];

  for (let row = 0; row < rows; row += 1) {
    for (let column = 0; column < columns; column += 1) {
      const west = AREA.west + column * width;
      const south = AREA.south + row * height;
      const pick = Math.floor(noise(seedFrom(`zone-${row}-${column}`), row + column) * zones.length);

      features.push({
        type: "Feature",
        properties: {
          layer: "zoning",
          parcel_id: `p${row}-${column}`,
          zone: zones[Math.min(zones.length - 1, pick)],
          // A coarse floor-area ratio, the number a developer actually looks at.
          far: Math.round((1 + noise(seedFrom(`far-${row}-${column}`), row) * 4) * 10) / 10,
          source: SOURCE,
          license: "CC0",
          synthetic: true,
          note: "Simulated parcel. Real zoning is published as decisions and drawings.",
        },
        geometry: {
          type: "Polygon",
          coordinates: [[
            [Number(west.toFixed(5)), Number(south.toFixed(5))],
            [Number((west + width).toFixed(5)), Number(south.toFixed(5))],
            [Number((west + width).toFixed(5)), Number((south + height).toFixed(5))],
            [Number(west.toFixed(5)), Number((south + height).toFixed(5))],
            [Number(west.toFixed(5)), Number(south.toFixed(5))],
          ]],
        },
      });
    }
  }

  return features;
}

/**
 * Flood zones along the Saigon river, as bands with a return period.
 *
 * Shape and placement are plausible for the city; the hazard class is invented. A real flood
 * layer comes from the provincial hazard maps through the upload path.
 */
function floodFeatures() {
  const bands = [
    { level: "high", period: 5, offset: 0.0 },
    { level: "medium", period: 20, offset: 0.012 },
    { level: "low", period: 100, offset: 0.024 },
  ];

  return bands.map((band, index) => {
    const south = AREA.south + band.offset;
    const north = south + 0.018 + index * 0.004;
    const west = AREA.west + 0.02 + index * 0.01;
    const east = AREA.east - 0.02 - index * 0.01;

    return {
      type: "Feature",
      properties: {
        layer: "flood",
        level: band.level,
        return_period_years: band.period,
        source: SOURCE,
        license: "CC0",
        synthetic: true,
        note: "Simulated flood extent. Provincial hazard maps are not published as open polygons.",
      },
      geometry: {
        type: "Polygon",
        coordinates: [[
          [Number((west - 0.01).toFixed(5)), Number(south.toFixed(5))],
          [Number((east + 0.01).toFixed(5)), Number(south.toFixed(5))],
          [Number((east + 0.01).toFixed(5)), Number(north.toFixed(5))],
          [Number((west - 0.01).toFixed(5)), Number(north.toFixed(5))],
          [Number((west - 0.01).toFixed(5)), Number(south.toFixed(5))],
        ]],
      },
    };
  });
}

export function buildSample() {
  const features = [...hexFeatures(), ...zoningFeatures(), ...floodFeatures()];

  return {
    type: "FeatureCollection",
    properties: {
      area: AREA,
      centre: CENTRE,
      note: "Simulated land price, zoning and flood layers for Ho Chi Minh City. Every feature carries `synthetic: true` and a note saying what it is.",
      attribution: ATTRIBUTION,
    },
    features,
  };
}

const check = process.argv.includes("--check");
const collection = buildSample();
const json = `${JSON.stringify(collection)}\n`;

if (check) {
  const current = existsSync(OUT_FILE) ? readFileSync(OUT_FILE, "utf8") : null;
  if (current !== json) {
    console.error("data/data2map-real-estate.json is out of date. Run: node scripts/generate-real-estate.mjs");
    process.exit(1);
  }
  console.log(`Real-estate sample is up to date (${collection.features.length} features).`);
} else {
  writeFileSync(OUT_FILE, json, "utf8");
  const byLayer = collection.features.reduce((counts, feature) => {
    counts[feature.properties.layer] = (counts[feature.properties.layer] ?? 0) + 1;
    return counts;
  }, {});
  console.log(`Wrote ${collection.features.length} features (${(json.length / 1024).toFixed(0)} KB): ${JSON.stringify(byLayer)}`);
}
