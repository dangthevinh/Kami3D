#!/usr/bin/env node
/**
 * What is actually inside each model file: nodes, meshes, and whether any of them is named.
 *
 *   node scripts/probe-model-structure.mjs            # report
 *   node scripts/probe-model-structure.mjs --write    # write data/model-structure.json
 *
 * Phase 29 asks for three things a building viewer usually has - **walk inside**, **toggle floors**,
 * **toggle furniture** - and all three need an asset whose parts exist as separate, nameable things. So
 * before any of it is built, this measures the catalogue it would have to run on.
 *
 * Measured on the 47 landmark models:
 *
 *   - **30 of 47 have no named part at all.** Their meshes are unnamed primitive wrappers.
 *   - the 10 that do have names are named after their **material**, not their structure: "Material2",
 *     "Model_material1_0", "BuildingMesh-00000.005_BuildingMat-00006.005_0". There is no "Floor_1",
 *     no "Roof", no "Chair" anywhere in the catalogue.
 *   - the biggest files are the least structured: \`taj-mahal\` has 770 nodes and 259 meshes, none named;
 *     \`hagia-sophia\` has 308 and 203, none named.
 *
 * So "toggle the floors" is not a feature that can be built on this asset set, and the honest answer -
 * which is what the panel on a model page now prints - is the number of parts a file really has. A
 * toggle that switched nothing would be worse than no toggle, and this project has already learned that
 * lesson twice: a procedural model drawn instead of a real one, and a card that promised a file it did
 * not have.
 *
 * The file this writes is what the panel reads, so the page and the command cannot disagree.
 */

import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const WRITE = process.argv.includes("--write");

/** Every folder of shipped models. A catalogue added later is one more line. */
const FOLDERS = [
  { id: "animals", dir: "public/models" },
  { id: "landmarks", dir: "public/models/landmarks" },
  { id: "space", dir: "public/models/space" },
  { id: "plants", dir: "public/models/plants" },
  { id: "vehicles", dir: "public/models/vehicles" },
  // Added when buildings became a harvested catalogue of its own. A folder that does not exist yet is
  // skipped rather than fatal: the entry is here because the catalogue is, and the harvest and the
  // model pipeline fill it in their own passes.
  { id: "buildings", dir: "public/models/buildings" },
];

/** A name that says what a part is, rather than which primitive it wrapped. */
const GENERIC = /^(object|mesh|node|group|scene|primitive|circle|plane|cylinder|cube|box|sphere|empty|solid|curve|shape|part|component|polygon|poly)[\s._-]*\d*$/i;
const isNamed = (name) => typeof name === "string" && name.trim().length > 0 && !GENERIC.test(name.trim());

function inspect(file) {
  const buffer = readFileSync(file);
  const json = JSON.parse(buffer.slice(20, 20 + buffer.readUInt32LE(12)).toString("utf8"));
  const meshNodes = (json.nodes ?? []).filter((node) => node.mesh !== undefined);
  const named = meshNodes.map((node) => node.name).filter(isNamed);

  return {
    nodes: (json.nodes ?? []).length,
    meshes: (json.meshes ?? []).length,
    namedParts: named.length,
    /** A few examples, so a reader can see *how* a file names things. */
    examples: named.slice(0, 3),
  };
}

const structure = {};
const summary = [];

for (const folder of FOLDERS) {
  const directory = join(ROOT, folder.dir);
  if (!existsSync(directory)) continue;
  for (const name of readdirSync(directory).filter((entry) => entry.endsWith(".glb")).sort()) {
    const slug = name.replace(".glb", "");
    const record = inspect(join(directory, name));
    structure[`${folder.id}/${slug}`] = record;
    summary.push({ catalogue: folder.id, slug, ...record });
  }
}

for (const catalogue of FOLDERS) {
  const rows = summary.filter((row) => row.catalogue === catalogue.id);
  if (rows.length === 0) continue;
  const withParts = rows.filter((row) => row.namedParts >= 3).length;
  console.log(
    catalogue.id.padEnd(12) + rows.length.toString().padStart(4) + " models · " +
      withParts.toString().padStart(3) + " with three or more named parts · " +
      rows.filter((row) => row.namedParts === 0).length.toString().padStart(3) + " with none",
  );
}

if (WRITE) {
  const sorted = Object.fromEntries(Object.entries(structure).sort(([a], [b]) => a.localeCompare(b)));
  writeFileSync(
    join(ROOT, "data", "model-structure.json"),
    JSON.stringify(
      {
        note:
          "Generated by scripts/probe-model-structure.mjs. What is really inside each shipped .glb: node " +
          "and mesh counts, and how many of them carry a name that says what the part is. Phase 29's " +
          "floor and furniture toggles need named parts, and this is the measurement of how many exist.",
        models: sorted,
      },
      null,
      2,
    ) + "\n",
    "utf8",
  );
  console.log("\nwrote data/model-structure.json with " + Object.keys(sorted).length + " models");
} else {
  console.log("\nDry run. Add --write to record this in data/model-structure.json.");
}
